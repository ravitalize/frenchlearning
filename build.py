#!/usr/bin/env python3
"""Bundle the weekly notes into data/notes.js so the site also works when opened as a local file.

Run after adding or editing a file in notes/:
    python3 build.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).parent
NOTES_DIR = ROOT / "notes"
OUT = ROOT / "data" / "notes.js"


def section(md: str, name: str) -> str:
    m = re.search(rf"^## {name}\s*$(.*?)(?=^## |\Z)", md, re.M | re.S)
    return m.group(1) if m else ""


def numbered(block: str) -> list[str]:
    return [m.group(1).strip() for m in re.finditer(r"^\d+\.\s+(.*)$", block, re.M)]


def main() -> None:
    weeks = []
    for path in sorted(NOTES_DIR.glob("week-*.md")):
        md = path.read_text(encoding="utf-8")
        title = re.search(r"^# (.*)$", md, re.M).group(1).strip()
        num = int(re.search(r"week-(\d+)", path.stem).group(1))
        questions = numbered(section(md, "Practice"))
        answers = numbered(section(md, "Answers"))
        if len(questions) != len(answers):
            raise SystemExit(f"{path.name}: {len(questions)} questions but {len(answers)} answers")
        # Notes shown on the Notes page stop before Practice; practice lives in the Quiz page.
        notes_md = re.split(r"^## Practice\s*$", md, maxsplit=1, flags=re.M)[0].strip()
        weeks.append({
            "id": num,
            "file": f"notes/{path.name}",
            "title": title,
            "markdown": notes_md,
            "questions": [{"q": q, "a": a} for q, a in zip(questions, answers)],
        })
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by build.py from notes/*.md. Do not edit by hand.\n"
        "window.NOTES = " + json.dumps(weeks, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    total = sum(len(w["questions"]) for w in weeks)
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(weeks)} weeks, {total} questions")


if __name__ == "__main__":
    main()
